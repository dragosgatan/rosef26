from __future__ import annotations

import glob
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

MODELS = {"seed42": "ddo1", "ddo_llama3_seed42": "ddo1", "additive_seed42": "blend1", "original": "original"}


def main() -> None:
    runs = []
    for f in sorted(glob.glob(str(REPO / "results/*/*.json"))):
        folder, name = Path(f).parent.name, Path(f).stem
        model = "original" if (folder, name) == ("seed42", "undefended") else MODELS.get(folder)
        if model is None:
            continue
        d = json.loads(Path(f).read_text())
        runs.append({"model": model, "attack": "rfa", "undo": d["undo"], "m": d["m"],
                     "scope": {"6-14": "ddo", "all": "all"}[d["layers"]],
                     "asr": round(100 * d["asr"]["llamaguard2"]), "found": d.get("decoys_zeroed")})

    benign = {}
    for name, model in MODELS.items():
        f = REPO / f"results/benign/{name}.json"
        if f.exists():
            benign[model] = {"none": round(100 * json.loads(f.read_text())["refusal_rate"])}

    data = {"ddoLayers": list(range(6, 15)), "runs": runs, "benign": benign}
    out = REPO / "kiosk/public/data.js"
    out.write_text("// Generated by stats/make_kiosk_data.py; do not edit by hand.\n"
                   f"window.KIOSK_DATA = {json.dumps(data, separators=(',', ':'))};\n")
    print(f"wrote {out.relative_to(REPO)}: {len(runs)} runs")


if __name__ == "__main__":
    main()
